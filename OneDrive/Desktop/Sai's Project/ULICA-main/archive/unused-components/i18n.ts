export class I18nService {
  private currentLanguage: Language = 'en';
  private translations: Record<Language, Translation> = translations;

  constructor() {
    // Load language from localStorage or detect from browser
    this.loadLanguage();
  }

  private loadLanguage(): void {
    if (typeof window !== 'undefined') {
      const savedLanguage = localStorage.getItem('ulica_language') as Language;
      if (savedLanguage && supportedLanguages.some(lang => lang.code === savedLanguage)) {
        this.currentLanguage = savedLanguage;
      } else {
        // Detect browser language
        const browserLanguage = navigator.language.split('-')[0] as Language;
        if (supportedLanguages.some(lang => lang.code === browserLanguage)) {
          this.currentLanguage = browserLanguage;
        }
      }
    }
  }

  setLanguage(language: Language): void {
    this.currentLanguage = language;
    if (typeof window !== 'undefined') {
      localStorage.setItem('ulica_language', language);
    }
  }

  getCurrentLanguage(): Language {
    return this.currentLanguage;
  }

  getSupportedLanguages(): LanguageConfig[] {
    return supportedLanguages;
  }

  t(key: string, params?: Record<string, string | number>): string {
    const keys = key.split('.');
    let value: any = this.translations[this.currentLanguage];

    for (const k of keys) {
      if (value && typeof value === 'object' && k in value) {
        value = value[k];
      } else {
        // Fallback to English
        value = this.translations.en;
        for (const fallbackKey of keys) {
          if (value && typeof value === 'object' && fallbackKey in value) {
            value = value[fallbackKey];
          } else {
            return key; // Return key if translation not found
          }
        }
        break;
      }
    }

    if (typeof value !== 'string') {
      return key;
    }

    // Replace parameters
    if (params) {
      return value.replace(/\{\{(\w+)\}\}/g, (match, param) => {
        return params[param]?.toString() || match;
      });
    }

    return value;
  }

  // Format currency based on language
  formatCurrency(amount: number, currency: string = 'INR'): string {
    const locale = this.getLocale();
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: currency,
    }).format(amount);
  }

  // Format date based on language
  formatDate(date: Date | string): string {
    const locale = this.getLocale();
    const dateObj = typeof date === 'string' ? new Date(date) : date;
    return new Intl.DateTimeFormat(locale).format(dateObj);
  }

  // Format number based on language
  formatNumber(number: number): string {
    const locale = this.getLocale();
    return new Intl.NumberFormat(locale).format(number);
  }

  private getLocale(): string {
    const languageMap: Record<Language, string> = {
      en: 'en-US',
      hi: 'hi-IN',
      es: 'es-ES',
      fr: 'fr-FR',
      de: 'de-DE',
      ja: 'ja-JP',
      ko: 'ko-KR',
      zh: 'zh-CN',
    };
    return languageMap[this.currentLanguage] || 'en-US';
  }
}

export const i18n = new I18nService();
